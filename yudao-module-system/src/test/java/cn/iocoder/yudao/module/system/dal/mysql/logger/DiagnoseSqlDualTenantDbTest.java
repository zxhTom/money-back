    private List<Map<String, Object>> executeProductionStatement(String statementId, Map<String, Object> paramMap) throws Exception {
        MappedStatement ms = mybatisConfiguration.getMappedStatement(statementId);
        assertNotNull(ms, "生产 MappedStatement 必须已注册: " + statementId);

        BoundSql boundSql = ms.getBoundSql(paramMap);
        String sql = boundSql.getSql();

        // 仅为 H2 将生产 DATE_SUB(NOW(), INTERVAL ? DAY/HOUR) 转换为等价 DATEADD 方言，保留所有表、字段、JOIN、WHERE与参数映射
        String h2Sql = sql
                .replaceAll("(?i)DATE_SUB\\(NOW\\(\\),\\s*INTERVAL\\s+(\\S+)\\s+DAY\\)", "DATEADD('DAY', -$1, NOW())")
                .replaceAll("(?i)DATE_SUB\\(NOW\\(\\),\\s*INTERVAL\\s+(\\S+)\\s+HOUR\\)", "DATEADD('HOUR', -$1, NOW())");

        List<ParameterMapping> parameterMappings = boundSql.getParameterMappings();

        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(h2Sql)) {
            for (int i = 0; i < parameterMappings.size(); i++) {
                String propName = parameterMappings.get(i).getProperty();
                Object val;
                if (boundSql.hasAdditionalParameter(propName)) {
                    val = boundSql.getAdditionalParameter(propName);
                } else if (paramMap.containsKey(propName)) {
                    val = paramMap.get(propName);
                } else {
                    val = mybatisConfiguration.newMetaObject(paramMap).getValue(propName);
                }
                ps.setObject(i + 1, val);
            }

            try (ResultSet rs = ps.executeQuery()) {
                ResultSetMetaData meta = rs.getMetaData();
                int colCount = meta.getColumnCount();
                List<Map<String, Object>> list = new ArrayList<>();
                while (rs.next()) {
                    Map<String, Object> row = new LinkedHashMap<>();
                    for (int c = 1; c <= colCount; c++) {
                        String colName = meta.getColumnLabel(c);
                        row.put(colName.toUpperCase(Locale.ROOT), rs.getObject(c));
                    }
                    list.add(row);
                }
                return list;
            }
        }
    }

    @Test
    public void testProductionLoginLogMapperQueriesOnRealH2() throws Exception {
        // 1. selectDiagnoseIpUserRefs (生产语句执行与双租户隔离)
        Map<String, Object> p1 = new HashMap<>();
        p1.put("tenantId", 1L);
        p1.put("days", 7);
        List<Map<String, Object>> t1LoginRefs = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseIpUserRefs", p1);
        assertEquals(2, t1LoginRefs.size(), "租户1包含两条不同IP记录");
        Set<String> t1Ips = new HashSet<>();
        for (Map<String, Object> row : t1LoginRefs) {
            t1Ips.add((String) row.get("IP"));
            assertEquals(101L, ((Number) row.get("USERID")).longValue());
            assertEquals("admin1", row.get("USERNAME"));
        }
        assertTrue(t1Ips.contains("10.1.1.1"));
        assertTrue(t1Ips.contains("10.1.1.2"));
        assertFalse(t1Ips.contains("10.1.2.1"), "MEMBER 必须被排除");
        assertFalse(t1Ips.contains("10.1.3.1"), "已删除用户必须被排除");
        assertFalse(t1Ips.contains("10.1.1.99"), "已删除日志必须被排除");
        assertFalse(t1Ips.contains("10.9.9.9"), "未知用户必须被排除");

        Map<String, Object> p2 = new HashMap<>();
        p2.put("tenantId", 2L);
        p2.put("days", 7);
        List<Map<String, Object>> t2LoginRefs = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseIpUserRefs", p2);
        assertEquals(1, t2LoginRefs.size(), "租户2只有1条记录");
        assertEquals("10.2.2.2", t2LoginRefs.get(0).get("IP"));
        assertEquals(201L, ((Number) t2LoginRefs.get(0).get("USERID")).longValue());

        // 2. selectDiagnoseUserLoginStats
        Map<String, Object> statP1 = Collections.singletonMap("tenantId", 1L);
        List<Map<String, Object>> t1Stats = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseUserLoginStats", statP1);
        assertEquals(1, t1Stats.size(), "租户1仅有 admin1 一条聚合统计");
        assertEquals(101L, ((Number) t1Stats.get(0).get("USERID")).longValue());
        assertEquals(2, ((Number) t1Stats.get(0).get("LOGINCOUNT")).intValue());
        assertEquals(1, ((Number) t1Stats.get(0).get("FAILCOUNT")).intValue());
        assertEquals(2, ((Number) t1Stats.get(0).get("DISTINCTIPCOUNT")).intValue());

        Map<String, Object> statP2 = Collections.singletonMap("tenantId", 2L);
        List<Map<String, Object>> t2Stats = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseUserLoginStats", statP2);
        assertEquals(1, t2Stats.size(), "租户2仅有 admin2 统计");
        assertEquals(201L, ((Number) t2Stats.get(0).get("USERID")).longValue());
        assertEquals(1, ((Number) t2Stats.get(0).get("LOGINCOUNT")).intValue());
        assertEquals(0, ((Number) t2Stats.get(0).get("FAILCOUNT")).intValue());

        // 3. selectDiagnoseUserLoginCountLastHour
        List<Map<String, Object>> hourStats1 = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseUserLoginCountLastHour", statP1);
        assertEquals(1, hourStats1.size());
        assertEquals(101L, ((Number) hourStats1.get(0).get("USERID")).longValue());
        assertEquals(2, ((Number) hourStats1.get(0).get("LOGINCOUNTLASTHOUR")).intValue());

        // 4. selectDiagnoseLastLoginIp
        Map<String, Object> lastIpP1 = new HashMap<>();
        lastIpP1.put("tenantId", 1L);
        lastIpP1.put("userId", 101L);
        List<Map<String, Object>> lastIpRes1 = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseLastLoginIp", lastIpP1);
        assertEquals(1, lastIpRes1.size());
        assertNotNull(lastIpRes1.get(0).get("USER_IP"));

        // 跨租户查最近 IP 必须为空
        Map<String, Object> lastIpCross = new HashMap<>();
        lastIpCross.put("tenantId", 2L);
        lastIpCross.put("userId", 101L);
        List<Map<String, Object>> lastIpCrossRes = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseLastLoginIp", lastIpCross);
        assertTrue(lastIpCrossRes.isEmpty(), "跨租户查用户最近 IP 必须为空");

        // 5. selectDiagnoseDistinctIpsByUserId
        List<Map<String, Object>> distinctIps1 = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseDistinctIpsByUserId", lastIpP1);
        assertEquals(2, distinctIps1.size());
        List<Map<String, Object>> distinctIpsCross = executeProductionStatement(LoginLogMapper.class.getName() + ".selectDiagnoseDistinctIpsByUserId", lastIpCross);
        assertTrue(distinctIpsCross.isEmpty(), "跨租户查用户不同 IP 必须为空");
    }

