    public byte[] generateAuthorizationConfirmationPdf() throws IOException {
        try (PDDocument document = new PDDocument();
             ByteArrayOutputStream baos = new ByteArrayOutputStream()) {

            // 1. 加载中文字体 (SimSun.ttf 假设放在 src/main/resources/fonts/)
            PDType0Font font;
            try (InputStream fontStream = new ClassPathResource("fonts/NotoSansSC-Regular.ttf").getInputStream()) {
                font = PDType0Font.load(document, fontStream);
            } catch (IOException e) {
                // 实际项目中应处理字体文件未找到的异常
                System.err.println("Font file not found or failed to load: " + e.getMessage());
                throw new IOException("Failed to load font file.", e);
            }

            // 2. 准备内容
            List<String> confirmationContent = getAuthorizationConfirmationContent();

            // 3. 绘制PDF
            PDPage page = new PDPage();
            document.addPage(page);
            PDPageContentStream contentStream = new PDPageContentStream(document, page);
            contentStream.setFont(font, FONT_SIZE_NORMAL);

            float y = page.getMediaBox().getHeight() - MARGIN;
            float startX = MARGIN;
            float width = page.getMediaBox().getWidth() - 2 * MARGIN;

            for (String line : confirmationContent) {
                // 检查是否需要换页
                if (y < MARGIN) {
                    contentStream.close();
                    page = new PDPage();
                    document.addPage(page);
                    contentStream = new PDPageContentStream(document, page);
                    contentStream.setFont(font, FONT_SIZE_NORMAL);
                    y = page.getMediaBox().getHeight() - MARGIN; // 重置Y坐标
                }

                // 识别标题和章节
                if (line.contains("授权确认书") && line.length() < 10) {
                    // 主标题
                    contentStream.setFont(font, FONT_SIZE_TITLE);
                    y -= FONT_SIZE_TITLE;
                    float titleWidth = font.getStringWidth(line) / 1000 * FONT_SIZE_TITLE;
                    float titleX = (page.getMediaBox().getWidth() - titleWidth) / 2;
                    contentStream.beginText();
                    contentStream.newLineAtOffset(titleX, y);
                    contentStream.showText(line);
                    contentStream.endText();
                    y -= LEADING * 2; // 标题后多留空行
                    contentStream.setFont(font, FONT_SIZE_NORMAL);
                    continue;
                } else if (line.matches("^(第.条).*")) {
                    // 章节标题 (如: 第一条 定义)
                    contentStream.setFont(font, FONT_SIZE_SECTION);
                    y -= FONT_SIZE_SECTION;
                    contentStream.beginText();
                    contentStream.newLineAtOffset(startX, y);
                    contentStream.showText(line);
                    contentStream.endText();
                    y -= LEADING; // 章节标题后留空行
                    contentStream.setFont(font, FONT_SIZE_NORMAL);
                    continue;
                } else if (line.trim().isEmpty()) {
                    // 空行
                    y -= LEADING / 2;
                    continue;
                }

                // 正常文本处理
                List<String> lines = splitTextToFit(line, font, FONT_SIZE_NORMAL, width);
                for (String text : lines) {
                    if (y < MARGIN) {
                        contentStream.close();
                        page = new PDPage();
                        document.addPage(page);
                        contentStream = new PDPageContentStream(document, page);
                        contentStream.setFont(font, FONT_SIZE_NORMAL);
                        y = page.getMediaBox().getHeight() - MARGIN;
                    }

                    // 尝试实现首行缩进
                    float currentX = startX;
                    if (text.trim().matches("^[\\d\\.]+\\s?.*")) {
                        // 编号行不缩进
                        currentX = startX;
                    } else if (lines.indexOf(text) == 0 && !line.matches("^(第.条).*")) {
                        // 段落首行缩进
                        currentX = startX + FONT_SIZE_NORMAL * 2;
                    }

                    y -= LEADING;
                    contentStream.beginText();
                    contentStream.newLineAtOffset(currentX, y);
                    contentStream.showText(text);
                    contentStream.endText();
                }
            }

            contentStream.close();
            document.save(baos);
            return baos.toByteArray();

        } catch (Exception e) {
            e.printStackTrace();
            throw new IOException("Failed to generate PDF: " + e.getMessage(), e);
        }
    }

    /**
     * 文本分割以适应页面宽度
     */
    private List<String> splitTextToFit(String text, PDType0Font font, float fontSize, float width) throws IOException {
        List<String> lines = new java.util.ArrayList<>();
        int lastSpace = -1;
        while (text.length() > 0) {
            int startIndex = 0;
            float size = 0;
            int currentIndex = 0;
            lastSpace = -1;
            while (currentIndex < text.length()) {
                char c = text.charAt(currentIndex);
                float charWidth = font.getStringWidth(String.valueOf(c)) / 1000 * fontSize;
                if (size + charWidth > width) {
                    break;
                }
                size += charWidth;
                if (c == ' ') {
                    lastSpace = currentIndex;
                }
                currentIndex++;
            }

            if (currentIndex == text.length()) {
                // 文本完全适应
                lines.add(text);
                text = "";
            } else if (lastSpace != -1) {
                // 在最后一个空格处分割
                lines.add(text.substring(0, lastSpace));
                text = text.substring(lastSpace + 1);
            } else {
                // 强制分割
                lines.add(text.substring(0, currentIndex));
                text = text.substring(currentIndex);
            }
        }
        return lines;
    }

